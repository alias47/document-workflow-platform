export function filterApplicants(
  applicants: Applicant[],
  search: string,
  status: string,
  stage: string,
  staff: string,
): Applicant[] {
  return applicants.filter((a) => {
    const fullName = `${a.firstName} ${a.lastName}`.toLowerCase();
    const matchSearch =
      !search ||
      fullName.includes(search.toLowerCase()) ||
      a.applicantNumber.toLowerCase().includes(search.toLowerCase()) ||
      a.email.toLowerCase().includes(search.toLowerCase());
    const matchStatus = status === 'all' || a.status === status;
    const matchStage = stage === 'all' || a.workflow.currentStage === stage;
    const matchStaff = staff === 'all' || a.assignedStaff === staff;
    return matchSearch && matchStatus && matchStage && matchStaff;
  });
}
